"""Validate TenderScrapers source outputs against 00_Config/sources_registry.xlsx.

This validator is aligned to the restructured framework:
- source scripts should live in 02_Sources/[Source]/00_Scripts;
- raw files should be generated by each scraper in 01_RawData;
- master/delta/updates/top-delta files should be in 02_Outputs;
- logs should be in 03_Logs;
- state files should be in 04_State.

The validator writes central reports to 05_SystemLogs/Validation.
"""
from __future__ import annotations

import argparse
from datetime import datetime
from pathlib import Path
from typing import Any

import pandas as pd


HERE = Path(__file__).resolve().parent
DEFAULT_PROJECT_ROOT = HERE
DEFAULT_REGISTRY = HERE / "00_Config" / "sources_registry.xlsx"
REGISTRY_SHEET = "Sources_Registry"

STANDARD_SOURCE_SUBFOLDERS = [
    "00_Scripts",
    "01_RawData",
    "02_Outputs",
    "03_Logs",
    "04_State",
    "05_Metadata",
]

OUTPUT_COLUMNS = {
    "master": "master_output_path",
    "delta": "delta_output_path",
    "updates": "updates_output_path",
    "top_delta": "top_delta_output_path",
}

OPTIONAL_PATH_COLUMNS = {
    "log": "log_path",
    "state": "state_path",
    "metadata": "metadata_path",
}


def _now_stamp() -> str:
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def _normalise_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    if value is None:
        return False
    try:
        if pd.isna(value):
            return False
    except TypeError:
        pass
    text = str(value).strip().casefold()
    return text in {"true", "yes", "y", "1", "active", "enabled"}


def _safe_text(value: Any) -> str:
    if value is None:
        return ""
    try:
        if pd.isna(value):
            return ""
    except TypeError:
        pass
    return str(value).strip()


def _resolve(project_root: Path, path_value: Any) -> Path:
    text = _safe_text(path_value)
    if not text:
        return Path()
    path = Path(text.replace("\\", "/"))
    if path.is_absolute():
        return path
    return project_root / path


def load_registry(registry_path: Path) -> pd.DataFrame:
    if not registry_path.exists():
        raise FileNotFoundError(f"Source registry not found: {registry_path}")

    df = pd.read_excel(registry_path, sheet_name=REGISTRY_SHEET, engine="openpyxl")
    df.columns = [str(c).strip() for c in df.columns]
    required = {"source_name", "source_key", "active", "folder_name", "script_path"}
    missing = sorted(required - set(df.columns))
    if missing:
        raise ValueError(f"Registry is missing required column(s): {', '.join(missing)}")

    df = df[df["source_name"].notna()].copy()
    df["active_bool"] = df["active"].apply(_normalise_bool)
    return df


def _status(path: Path) -> str:
    return "OK" if path.exists() else "MISSING"


def _add_check(
    rows: list[dict[str, Any]],
    *,
    source_name: str,
    source_key: str,
    active: bool,
    check_type: str,
    label: str,
    path: Path,
    required: bool,
    message: str = "",
) -> None:
    exists = path.exists() if str(path) else False
    rows.append(
        {
            "checked_at": datetime.now().isoformat(timespec="seconds"),
            "source_name": source_name,
            "source_key": source_key,
            "active": active,
            "check_type": check_type,
            "label": label,
            "required": required,
            "status": "OK" if exists else "MISSING",
            "path": str(path),
            "message": message,
        }
    )


def validate_source(
    *,
    project_root: Path,
    source: pd.Series,
    include_inactive: bool,
    require_logs_and_state: bool,
) -> list[dict[str, Any]]:
    source_name = _safe_text(source.get("source_name"))
    source_key = _safe_text(source.get("source_key")) or source_name
    active = bool(source.get("active_bool", False))
    folder_name = _safe_text(source.get("folder_name"))

    rows: list[dict[str, Any]] = []

    if not active and not include_inactive:
        rows.append(
            {
                "checked_at": datetime.now().isoformat(timespec="seconds"),
                "source_name": source_name,
                "source_key": source_key,
                "active": active,
                "check_type": "source",
                "label": "inactive",
                "required": False,
                "status": "SKIPPED_INACTIVE",
                "path": "",
                "message": "Source inactive in sources_registry.xlsx.",
            }
        )
        return rows

    source_root = project_root / "02_Sources" / folder_name if folder_name else Path()
    _add_check(
        rows,
        source_name=source_name,
        source_key=source_key,
        active=active,
        check_type="folder",
        label="source_root",
        path=source_root,
        required=active,
    )

    for subfolder in STANDARD_SOURCE_SUBFOLDERS:
        _add_check(
            rows,
            source_name=source_name,
            source_key=source_key,
            active=active,
            check_type="folder",
            label=subfolder,
            path=source_root / subfolder,
            required=active,
        )

    script_path = _resolve(project_root, source.get("script_path"))
    _add_check(
        rows,
        source_name=source_name,
        source_key=source_key,
        active=active,
        check_type="script",
        label="script_path",
        path=script_path,
        required=active,
    )

    for label, column in OUTPUT_COLUMNS.items():
        if column in source.index:
            _add_check(
                rows,
                source_name=source_name,
                source_key=source_key,
                active=active,
                check_type="output",
                label=label,
                path=_resolve(project_root, source.get(column)),
                required=active,
            )

    for label, column in OPTIONAL_PATH_COLUMNS.items():
        if column in source.index:
            required = active and require_logs_and_state and label in {"log", "state"}
            _add_check(
                rows,
                source_name=source_name,
                source_key=source_key,
                active=active,
                check_type=label,
                label=label,
                path=_resolve(project_root, source.get(column)),
                required=required,
                message="Optional unless --require-logs-and-state is used." if not required else "",
            )

    return rows


def write_report(rows: list[dict[str, Any]], output_root: Path) -> tuple[Path, Path | None]:
    output_root.mkdir(parents=True, exist_ok=True)
    ts = _now_stamp()
    df = pd.DataFrame(rows)

    csv_path = output_root / f"validation_report_{ts}.csv"
    xlsx_path = output_root / f"validation_report_{ts}.xlsx"

    df.to_csv(csv_path, index=False)

    try:
        with pd.ExcelWriter(
            xlsx_path,
            engine="xlsxwriter",
            engine_kwargs={"options": {"strings_to_urls": False}},
        ) as writer:
            df.to_excel(writer, index=False, sheet_name="Validation")
            worksheet = writer.sheets["Validation"]
            worksheet.freeze_panes(1, 0)
            for idx, col in enumerate(df.columns):
                width = min(max(len(str(col)) + 2, 12), 80)
                worksheet.set_column(idx, idx, width)
    except Exception as exc:  # pragma: no cover
        print(f"WARNING: Could not write Excel validation report: {exc}")
        return csv_path, None

    return csv_path, xlsx_path


def print_console_summary(rows: list[dict[str, Any]]) -> None:
    df = pd.DataFrame(rows)
    if df.empty:
        print("No validation rows produced.")
        return

    active_df = df[df["active"] == True].copy()  # noqa: E712
    missing_required = active_df[(active_df["required"] == True) & (active_df["status"] == "MISSING")]  # noqa: E712

    print("\nValidation summary")
    print("------------------")
    print(f"Total checks: {len(df)}")
    print(f"Missing required checks: {len(missing_required)}")

    if not missing_required.empty:
        print("\nMissing required items:")
        for _, row in missing_required.iterrows():
            print(f"- {row['source_name']} | {row['check_type']}:{row['label']} | {row['path']}")

    inactive = df[df["status"] == "SKIPPED_INACTIVE"]
    if not inactive.empty:
        print("\nInactive sources skipped:")
        for name in inactive["source_name"].drop_duplicates().tolist():
            print(f"- {name}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Validate source scripts and output files against sources_registry.xlsx.")
    parser.add_argument("--project-root", default=str(DEFAULT_PROJECT_ROOT), help="02_TenderScrapers project root.")
    parser.add_argument("--registry", default=str(DEFAULT_REGISTRY), help="Path to 00_Config/sources_registry.xlsx.")
    parser.add_argument("--include-inactive", action="store_true", help="Validate inactive sources as well.")
    parser.add_argument(
        "--require-logs-and-state",
        action="store_true",
        help="Treat registry log_path and state_path as required after a completed run.",
    )
    args = parser.parse_args()

    project_root = Path(args.project_root).resolve()
    registry_path = Path(args.registry).resolve()
    validation_root = project_root / "05_SystemLogs" / "Validation"

    print(f"Project root: {project_root}")
    print(f"Registry: {registry_path}")

    registry = load_registry(registry_path)

    rows: list[dict[str, Any]] = []
    for _, source in registry.iterrows():
        rows.extend(
            validate_source(
                project_root=project_root,
                source=source,
                include_inactive=args.include_inactive,
                require_logs_and_state=args.require_logs_and_state,
            )
        )

    print_console_summary(rows)

    csv_path, xlsx_path = write_report(rows, validation_root)
    print(f"\nValidation report: {csv_path}")
    if xlsx_path:
        print(f"Validation report Excel: {xlsx_path}")

    df = pd.DataFrame(rows)
    missing_required = df[(df["active"] == True) & (df["required"] == True) & (df["status"] == "MISSING")]  # noqa: E712
    return 1 if not missing_required.empty else 0


if __name__ == "__main__":
    raise SystemExit(main())
